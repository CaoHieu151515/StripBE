package com.example.strip.Models;

public class PackageDriver {
    private int id;
    private String packageID;
    private double price;
    private String name;
    private String description;
    private int time;
    private int bonus;
    private String status;

    public int getId() {
        return id;
    }

    public String getPackageID() {
        return packageID;
    }

    public double getPrice() {
        return price;
    }

    public String getName() {
        return name;
    }

    public String getDescription() {
        return description;
    }

    public int getBonus() {
        return bonus;
    }

    public int getTime() {
        return time;
    }

    public String getStatus() {
        return status;
    }
}

